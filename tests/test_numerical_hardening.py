def test_training_step_gradient_uses_current_state(monkeypatch):
    from puremacro.vfi.deep_macro import DeepMacroMLP, DeepMacroModel, solve_deep_macro
    forward, backward = DeepMacroMLP.forward, DeepMacroMLP.backward
    current_input = []
    checked = []

    def record(self, x):
        if np.asarray(x).shape[0] == 4 and not current_input:
            current_input.append(np.array(x, copy=True))
        return forward(self, x)

    def check(self, upstream):
        actual = backward(self, upstream)
        # Check a full training-step VJP by finite differences with the Euler
        # target detached. Neither next-state activations nor target derivatives
        # belong in this gradient.
        h = 1e-6
        for array, gradient in zip(
            [a for pair in zip(self.weights, self.biases) for a in pair],
            [a for pair in actual for a in pair],
        ):
            numerical = np.zeros_like(array)
            for idx in np.ndindex(array.shape):
                original = array[idx]
                array[idx] = original + h
                plus = np.sum(forward(self, current_input[0]) * upstream)
                array[idx] = original - h
                minus = np.sum(forward(self, current_input[0]) * upstream)
                array[idx] = original
                numerical[idx] = (plus - minus) / (2*h)
            np.testing.assert_allclose(gradient, numerical, rtol=1e-6, atol=1e-10)
        checked.append(True)
        return actual

    monkeypatch.setattr(DeepMacroMLP, "forward", record)
    monkeypatch.setattr(DeepMacroMLP, "backward", check)
    solve_deep_macro(DeepMacroModel(n_states=1, n_controls=1), hidden_dims=(4,),
        n_epochs=1, trajectory_length=10, burn_in=2, batch_size=4)
    assert checked == [True]


@pytest.mark.parametrize("closure", ["lump_sum", "deficit_reduction"])
def test_reported_tariff_revenue_reconciles_fiscal_budget(calibration, closure):
    c = calibration
    tau = np.ones((4,2,2)); tau[2:, :, 0] = [[1.05, 1.15], [1.2, 1.3]]
    result = solve_trade_equilibrium(c, tau=tau, fiscal_closure=closure, tariff_revenue_mode="schedule", sigma=2, tol=1e-8, max_iter=150)
    assert result.converged
    # The calibration's generated final-demand tax is zero.
    taxes = np.sum(c.tax * result.y_sol, axis=1).ravel()
    np.testing.assert_allclose(result.T_sol.ravel(), taxes + result.tariffs, atol=1e-7)


