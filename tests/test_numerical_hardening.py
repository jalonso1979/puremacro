def test_malformed_dynare_risk_vector_is_not_resized_into_a_match():
    dr = canonical_growth_2nd_order().decision_rules()
    fields = {name: getattr(dr, name).to_numpy() for name in
              ("ys", "ghx", "ghu", "ghxx", "ghxu", "ghuu", "ghs2")}
    fields["ghs2"] = np.array([0.])
    raw = {"oo_": {"dr": fields}, "M_": {
        "endo_names": list(dr.variable_names), "exo_names": list(dr.shock_names),
        "state_var": [list(dr.variable_names).index(v)+1 for v in dr.state_variables]}}
    result = verify_dynare_parity(dr, raw, order=2)
    assert not result.passed and result.details["status"] == "UNAVAILABLE"
    assert "ghs2" in result.details["error"]
