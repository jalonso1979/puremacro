@pytest.mark.parametrize("rho", [.5, .8])
@pytest.mark.parametrize("equation", ["cubic", "lead_cubic", "quadratic_feedback"])
def test_third_order_risk_slopes_closed_form(rho, equation):
    beta, eta, sd = .95, .3, .1
    if equation == "cubic":
        rhs = "x^3"
        A = 1 / (1 - beta * rho**3)
        B = 3 * beta * A * rho * sd**2 / (1 - beta * rho)
    elif equation == "lead_cubic":
        rhs = "x(+1)^3+eta*x(+1)^2*x"
        A = (rho**3 + eta * rho**2) / (1 - beta * rho**3)
        B = (3 * beta * A * rho + 3 * rho + eta) * sd**2 / (1 - beta * rho)
    else:
        rhs = "x^2+eta*x*y(+1)"
        A = 1 / (1 - beta * rho**2)
        C = beta * A / (1 - beta)
        D = eta * A * rho**2 / (1 - beta * rho**3)
        B = (3 * beta * D * rho + eta * (A + C)) * sd**2 / (1 - beta * rho)
    sol = load_mod(f"""
        var x y; varexo e; parameters rho beta eta;
        rho={rho}; beta={beta}; eta={eta};
        model; x=rho*x(-1)+e; y=beta*y(+1)+{rhs}; end;
        initval; x=0;y=0;end; shocks;var e;stderr {sd};end;
    """, order=3)
    np.testing.assert_allclose(sol.ghxss[1, 0], 2 * B * rho, rtol=1e-10, atol=1e-12)
    np.testing.assert_allclose(sol.ghuss[1, 0], 2 * B, rtol=1e-10, atol=1e-12)


def test_third_order_correlated_shocks_and_multiple_states():
    rho, beta = .7, .95
    cov = np.array([[.01, .004], [.004, .04]])
    sol = load_mod("""
        var x z y; varexo e v; parameters rho beta; rho=.7;beta=.95;
        model; x=rho*x(-1)+e;z=rho*z(-1)+v;y=beta*y(+1)+(x+2*z)^3;end;
        initval;x=0;z=0;y=0;end;
        shocks;var e;stderr .1;var v;stderr .2;corr e,v=.2;end;
    """, order=3)
    loading = np.array([1., 2.])
    B = 3 * beta * rho * (loading @ cov @ loading) / ((1-beta*rho**3)*(1-beta*rho))
    np.testing.assert_allclose(sol.ghxss[2], 2 * B * rho * loading, rtol=1e-10)
    np.testing.assert_allclose(sol.ghuss[2], 2 * B * loading, rtol=1e-10)


