class TestCalibrateNestWeights:
    def _make_panel(self, base_year: int = 2000) -> pd.DataFrame:
        rng = np.random.default_rng(13)
        codes = ['US', 'DE', 'FR']
        rows = []
        for code in codes:
            for yr in range(1998, 2005):
                p_num = 1.0 + 0.1 * rng.random()
                p_den = 1.0 + 0.1 * rng.random()
                share = 0.3 + 0.1 * rng.random()
                rows.append({
                    'code': code, 'year': yr,
                    'p_num': p_num, 'p_den': p_den, 'share': share,
                })
        return pd.DataFrame(rows)

    def test_returns_dataframe_with_weight_col(self):
        panel = self._make_panel()
        result = calibrate_nest_weights(
            panel, sigma=1.5, share_col='share',
            p_num_col='p_num', p_den_col='p_den', base_year=2000,
        )
        assert isinstance(result, pd.DataFrame)
        assert 'alpha_c' in result.columns

    def test_cobb_douglas_limit(self):
        """At σ = 1, weight equals base-year cost share (no price correction)."""
