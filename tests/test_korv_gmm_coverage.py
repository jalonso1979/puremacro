class TestFitSigmaSuPooled:
    def _make_panel(self, n_per: int = 50, beta_true: float = 0.8) -> pd.DataFrame:
        """2SLS DGP: y = beta * x + eps; z is instrument correlated with x."""
        rng = np.random.default_rng(21)
        codes = ['A', 'B', 'C']
        chunks = []
        for code in codes:
            z    = rng.standard_normal(n_per)
            x    = 0.8 * z + 0.2 * rng.standard_normal(n_per)
            y    = -beta_true * x + 0.1 * rng.standard_normal(n_per)
            df_c = pd.DataFrame({
                'code': code,
                'dlog_ls_lu': y,
                'dlog_ws_wu': x,
                'dlog_ns_nu': z,
            })
            chunks.append(df_c)
        return pd.concat(chunks, ignore_index=True)

    def test_returns_sym_ces_fit(self):
        panel = self._make_panel()
        result = fit_sigma_su_pooled(panel)
        assert isinstance(result, SymCESFit)

    def test_sigma_su_populated_others_nan(self):
        panel = self._make_panel()
        result = fit_sigma_su_pooled(panel)
        assert np.isfinite(result.sigma_su)
        assert np.isnan(result.sigma_kl)
        assert np.isnan(result.sigma_ie)

    def test_converged_true(self):
        panel = self._make_panel()
        result = fit_sigma_su_pooled(panel)
        assert result.converged is True

    def test_hansen_j_is_none(self):
        """Single-equation 2SLS is just-identified."""
        panel = self._make_panel()
        result = fit_sigma_su_pooled(panel)
        assert result.hansen_J is None

    def test_recovers_true_beta(self):
        """2SLS should recover the true slope from a standard IV DGP."""
        beta_true = 0.8
        panel = self._make_panel(n_per=200, beta_true=beta_true)
        result = fit_sigma_su_pooled(panel)
        assert abs(result.sigma_su - beta_true) < 0.15, (
            f"sigma_su={result.sigma_su:.3f}, expected ~{beta_true}"
        )

    def test_degenerate_instrument_returns_nan(self):
        """Zero-variance instrument: 2SLS should return NaN sigma_su, converged=False."""
        rng = np.random.default_rng(29)
        codes = ['A', 'B']
        rows = []
        for code in codes:
            for _ in range(30):
                rows.append({
                    'code': code,
                    'dlog_ls_lu': rng.standard_normal(),
                    'dlog_ws_wu': rng.standard_normal(),
                    'dlog_ns_nu': 0.0,  # zero variance → degenerate
                })
        panel = pd.DataFrame(rows)
        result = fit_sigma_su_pooled(panel)
        assert np.isnan(result.sigma_su)
        assert result.converged is False


