# Helpers to build synthetic panels consistent with the KORV moment conditions
# ---------------------------------------------------------------------------

def _make_korv_panel(
    n: int = 80,
    sigma_su: float = 0.7,
    sigma_eu: float = 1.5,
    noise: float = 0.05,
    rng: np.random.Generator | None = None,
) -> pd.DataFrame:
    """Synthetic panel where FOCs hold at (sigma_su, sigma_eu) + small noise.

    The three KORV first-order conditions in log-differences are:
      Δlog(L_s/L_u)     = σ_su * Δlog(w_s/w_u)   + ε1
      Δlog(K_e/L_u)     = σ_eu * Δlog(w_u/P_K)   + ε2
      Δlog(LS_u_share)  = (1-σ_eu) * Δlog(P_K/P_C) + ε3

    We generate the RHS series from N(0,1) draws, compute LHS exactly from
    the FOC, and add small white noise so the GMM estimator faces a nearly-
    identified problem.
    """
    if rng is None:
        rng = np.random.default_rng(42)
    dlog_ws_wu  = rng.standard_normal(n)
    dlog_wu_pk  = rng.standard_normal(n)
    dlog_pk_pc  = rng.standard_normal(n)
    dlog_ls_lu    = -sigma_su       * dlog_ws_wu  + noise * rng.standard_normal(n)
    dlog_ke_lu    = sigma_eu        * dlog_wu_pk  + noise * rng.standard_normal(n)
    dlog_lsushare = (1 - sigma_eu)  * dlog_pk_pc  + noise * rng.standard_normal(n)
    return pd.DataFrame({
        'dlog_ls_lu':    dlog_ls_lu,
        'dlog_ws_wu':    dlog_ws_wu,
        'dlog_ke_lu':    dlog_ke_lu,
        'dlog_wu_pk':    dlog_wu_pk,
        'dlog_lsushare': dlog_lsushare,
        'dlog_pk_pc':    dlog_pk_pc,
        'k_equip_share_inner': np.full(n, 0.4),
    })


def _make_pooled_panel(
    n_countries: int = 4,
    n_per: int = 40,
    sigma_su: float = 0.7,
    sigma_eu: float = 1.5,
    noise: float = 0.05,
    rng: np.random.Generator | None = None,
) -> pd.DataFrame:
    """Multi-country panel suitable for pooled GMM estimators."""
    if rng is None:
        rng = np.random.default_rng(99)
    codes = [f"C{i}" for i in range(n_countries)]
    chunks = []
    for code in codes:
        chunk = _make_korv_panel(n=n_per, sigma_su=sigma_su, sigma_eu=sigma_eu,
                                  noise=noise, rng=rng)
        chunk['code'] = code
        chunks.append(chunk)
    return pd.concat(chunks, ignore_index=True)


