"""Multi-country, multi-sector trade model built on input-output tables.

The package namespace holds the calibration, equilibrium, solver, scenario,
Geary-Khamis, welfare and trade-policy (optimal tariffs, Nash tariff games,
Caliendo-Parro exact hat algebra), the flexible CGE extensions (nested CES
technology, Stone-Geary demand, Armington sourcing, variable markups), policy analytics (effective protection,
welfare decomposition, supply-chain exposure, tariff incidence), the exact
nested-CES block Newton (:mod:`puremacro.trade.ces_newton`), household demand
systems with money-metric welfare (:mod:`puremacro.trade.household`) and group
incidence (:mod:`puremacro.trade.distributional`), audited parameter
continuation and the fold helpers (:mod:`puremacro.trade.continuation`), the
reduced local-stability diagnostic (:mod:`puremacro.trade.stability`,
experimental), native MRIO tables with provenance, readers, regularization and
aggregation (:mod:`puremacro.trade.mrio`), the condensed one-factor Leontief
tariff model with an independent certificate (:mod:`puremacro.trade.condensed`),
the perfect-foresight dynamic MRIO with sector capital
(:mod:`puremacro.trade.dynamic`, experimental), joint sourcing/capital/labor
transitions (:mod:`puremacro.trade.reallocation`, experimental), plotting and GPU/MLX solver entry points (:mod:`puremacro.trade.gpu`; torch and mlx are
optional and imported on first use) and the result containers; data loaders
and the synthetic table live in :mod:`puremacro.trade.data` (for example
``from puremacro.trade.data import synthetic_icio_table``).
"""
