class ChoiceMapping(dict):
    """Dictionary of choice arrays supporting numpy array operations and elementwise comparisons."""

    def __array__(self, dtype: Any = None) -> np.ndarray:
        keys = sorted(self.keys())
        return np.array([self[k] for k in keys], dtype=dtype)

    def __ge__(self, other: Any) -> np.ndarray:
        return self.__array__() >= other

    def __le__(self, other: Any) -> np.ndarray:
        return self.__array__() <= other

    def __gt__(self, other: Any) -> np.ndarray:
        return self.__array__() > other

    def __lt__(self, other: Any) -> np.ndarray:
        return self.__array__() < other

    @property
    def shape(self) -> Tuple[int, ...]:
        return self.__array__().shape

    @property
    def ndim(self) -> int:
        return self.__array__().ndim

    def min(self, *args: Any, **kwargs: Any) -> Any:
        return self.__array__().min(*args, **kwargs)

    def max(self, *args: Any, **kwargs: Any) -> Any:
        return self.__array__().max(*args, **kwargs)


