@dataclass(frozen=True)
class DCEGMSolution:
    """Solution container for discrete-continuous models solved via DC-EGM.

    Parameters
    ----------
    asset_grid : np.ndarray
        Exogenous evaluation grid of cash-on-hand M.
    choice_policies : dict[int, np.ndarray] | ChoiceMapping
        Mapping from discrete choice d to continuous consumption policy c_d(M).
    choice_values : dict[int, np.ndarray] | ChoiceMapping
        Mapping from discrete choice d to conditional value function v_d(M).
    choice_probabilities : dict[int, np.ndarray] | ChoiceMapping
        Mapping from discrete choice d to conditional choice probability P(d | M).
    integrated_value : np.ndarray
        Inclusive integrated value function V(M) under taste shocks.
    converged : bool
        Whether the recursive dynamic programming algorithm converged.
    metadata : dict[str, Any]
        Solver diagnostics, iterations, tolerances, and execution metadata.
    """

    asset_grid: np.ndarray
    choice_policies: Dict[int, np.ndarray]
    choice_values: Dict[int, np.ndarray]
    choice_probabilities: Dict[int, np.ndarray]
    integrated_value: np.ndarray
    converged: bool
    metadata: Dict[str, Any] = field(default_factory=dict)

    @property
    def m_grid(self) -> np.ndarray:
        """Cash-on-hand evaluation grid."""
        return self.asset_grid

    @property
    def c(self) -> np.ndarray:
        """Array of consumption policies across choices, shape (n_choices, n_m)."""
        return np.array([self.choice_policies[d] for d in sorted(self.choice_policies.keys())])

    @property
    def v(self) -> np.ndarray:
        """Array of conditional values across choices, shape (n_choices, n_m)."""
        return np.array([self.choice_values[d] for d in sorted(self.choice_values.keys())])

    @property
    def probabilities(self) -> np.ndarray:
        """Array of choice probabilities, shape (n_choices, n_m)."""
        return np.array([self.choice_probabilities[d] for d in sorted(self.choice_probabilities.keys())])

    @property
    def probs(self) -> np.ndarray:
        """Alias for probabilities."""
        return self.probabilities

    @property
    def P(self) -> np.ndarray:
        """Alias for probabilities array."""
        return self.probabilities

    @property
    def aprime(self) -> Dict[int, np.ndarray]:
        """Next-period saving policies a' = M - c_d(M) for each choice d."""
        a_min = self.metadata.get("a_min", 0.0)
        return {
            d: np.maximum(self.asset_grid - self.choice_policies[d], a_min)
            for d in self.choice_policies
        }

    @property
    def n_iter(self) -> int:
        """Number of iterations performed."""
        return int(self.metadata.get("n_iter", 0))

    @property
    def sup_norm(self) -> float:
        """Final sup-norm error."""
        return float(self.metadata.get("sup_norm", 0.0))

    @property
    def backend(self) -> str:
        """Executed numerical backend."""
        return str(self.metadata.get("backend", "numpy"))

    @property
    def sigma_eps(self) -> float:
        """Scale parameter of taste shocks."""
        return float(self.metadata.get("sigma_eps", 0.0))

    def policy(
        self, s: Union[float, Sequence[float], np.ndarray], choice: Optional[int] = None
    ) -> Union[float, np.ndarray]:
        """Evaluate continuous consumption policy at arbitrary cash-on-hand state(s).

        Parameters
        ----------
        s : float | Sequence[float] | np.ndarray
            Cash-on-hand query points.
        choice : int, optional
            Discrete choice index d. If None, computes expected policy E[c(s)] = sum_d P(d|s) c_d(s).

        Returns
        -------
        float | np.ndarray
            Interpolated continuous policy values.
        """
        s_arr = np.asarray(s, dtype=np.float64)
        is_scalar = s_arr.ndim == 0

        if choice is not None:
            if choice not in self.choice_policies:
                raise ValueError(f"Invalid choice {choice}; choices: {list(self.choice_policies.keys())}")
            c_vals = np.interp(s_arr, self.asset_grid, self.choice_policies[choice])
            return float(c_vals) if is_scalar else c_vals

        # Expected policy across discrete choices
        c_exp = np.zeros_like(s_arr)
        for d in self.choice_policies:
            c_d = np.interp(s_arr, self.asset_grid, self.choice_policies[d])
            p_d = np.interp(s_arr, self.asset_grid, self.choice_probabilities[d])
            c_exp += p_d * c_d
        return float(c_exp) if is_scalar else c_exp

    def value(
        self, s: Union[float, Sequence[float], np.ndarray], choice: Optional[int] = None
    ) -> Union[float, np.ndarray]:
        """Evaluate value function at arbitrary cash-on-hand state(s).

        Parameters
        ----------
        s : float | Sequence[float] | np.ndarray
            Cash-on-hand query points.
        choice : int, optional
            Discrete choice index d. If None, evaluates inclusive integrated value V(s).

        Returns
        -------
        float | np.ndarray
            Interpolated continuous value(s).
        """
        s_arr = np.asarray(s, dtype=np.float64)
        is_scalar = s_arr.ndim == 0

        if choice is not None:
            if choice not in self.choice_values:
                raise ValueError(f"Invalid choice {choice}; choices: {list(self.choice_values.keys())}")
            v_vals = np.interp(s_arr, self.asset_grid, self.choice_values[choice])
            return float(v_vals) if is_scalar else v_vals

        v_inc = np.interp(s_arr, self.asset_grid, self.integrated_value)
        return float(v_inc) if is_scalar else v_inc

    def choice_prob(
        self, s: Union[float, Sequence[float], np.ndarray], choice: Optional[int] = None
    ) -> Union[float, np.ndarray]:
        """Evaluate discrete choice probabilities at arbitrary cash-on-hand state(s).

        Parameters
        ----------
        s : float | Sequence[float] | np.ndarray
            Cash-on-hand query points.
        choice : int, optional
            Discrete choice index d. If None, returns array of shape (n_choices, ...)
            with probabilities for all choices.

        Returns
        -------
        float | np.ndarray
            Interpolated choice probability values.
        """
        s_arr = np.asarray(s, dtype=np.float64)
        is_scalar = s_arr.ndim == 0

        if choice is not None:
            if choice not in self.choice_probabilities:
                raise ValueError(f"Invalid choice {choice}; choices: {list(self.choice_probabilities.keys())}")
            p_vals = np.interp(s_arr, self.asset_grid, self.choice_probabilities[choice])
            return float(p_vals) if is_scalar else p_vals

        all_probs = [
            np.interp(s_arr, self.asset_grid, self.choice_probabilities[d])
            for d in sorted(self.choice_probabilities.keys())
        ]
        res = np.array(all_probs)
        return res[:, 0] if (is_scalar and res.ndim > 1) else res

    def choice_probability(
        self, s: Union[float, Sequence[float], np.ndarray], choice: Optional[int] = None
    ) -> Union[float, np.ndarray]:
        """Alias for choice_prob."""
        return self.choice_prob(s, choice=choice)

    def summary(self) -> pd.DataFrame:
        """Structured summary DataFrame of DC-EGM solver results."""
        n_choices = len(self.choice_policies)
        elapsed = self.metadata.get("elapsed_time", np.nan)
        a_min = self.metadata.get("a_min", 0.0)
        beta = self.metadata.get("beta", np.nan)
        r = self.metadata.get("r", np.nan)

        rows = [
            {"Metric": "Method", "Value": "Discrete Choice EGM (DC-EGM)"},
            {"Metric": "Discrete Choices (D)", "Value": str(n_choices)},
            {"Metric": "Evaluation Grid Points (M)", "Value": str(len(self.asset_grid))},
            {"Metric": "Cash-on-Hand Range", "Value": f"[{self.asset_grid[0]:.4g}, {self.asset_grid[-1]:.4g}]"},
            {"Metric": "Taste Shock Scale (sigma_eps)", "Value": f"{self.sigma_eps:.4g}"},
            {"Metric": "Borrowing Limit (a_min)", "Value": f"{a_min:.4g}"},
            {"Metric": "Discount Factor (beta)", "Value": f"{beta:.4g}" if np.isfinite(beta) else "N/A"},
            {"Metric": "Interest Rate (r)", "Value": f"{r:.4g}" if np.isfinite(r) else "N/A"},
            {"Metric": "Converged", "Value": str(self.converged)},
            {"Metric": "Iterations", "Value": str(self.n_iter)},
            {"Metric": "Sup Norm", "Value": f"{self.sup_norm:.4e}"},
            {"Metric": "Backend", "Value": str(self.backend)},
            {"Metric": "Elapsed Time (s)", "Value": f"{elapsed:.4f}" if np.isfinite(elapsed) else "N/A"},
        ]
        return pd.DataFrame(rows).set_index("Metric")

    def to_frame(self) -> pd.DataFrame:
        """Return tabulations of policies, values, and probabilities on the grid."""
        df = pd.DataFrame({"M": self.asset_grid})
        for d in sorted(self.choice_policies.keys()):
            df[f"c_{d}"] = self.choice_policies[d]
            df[f"v_{d}"] = self.choice_values[d]
            df[f"prob_{d}"] = self.choice_probabilities[d]
        df["V_integrated"] = self.integrated_value
        return df

    def to_markdown(self, **kwargs: Any) -> str:
        """Render summary table as Markdown."""
        return _df_to_markdown(self.summary(), **kwargs)

    def to_latex(self, **kwargs: Any) -> str:
        """Render summary table as LaTeX tabular."""
        return _df_to_latex(self.summary(), **kwargs)

    def to_typst(self, **kwargs: Any) -> str:
        """Render summary table as Typst table."""
        return _df_to_typst(self.summary(), **kwargs)

    def plot(
        self, figsize: Tuple[float, float] = (12, 8), show: bool = False
    ) -> plt.Figure:
        """Plot diagnostic 4-panel figure of policies, values, and probabilities.

        Returns
        -------
        matplotlib.figure.Figure
            Figure instance containing the diagnostic subplots.
        """
        fig, axes = plt.subplots(2, 2, figsize=figsize, constrained_layout=True)
        colors = ["tab:blue", "tab:orange", "tab:green", "tab:red", "tab:purple", "tab:brown"]

        # Panel 1: Consumption Policies
        ax1 = axes[0, 0]
        for d, col in zip(sorted(self.choice_policies.keys()), colors):
            ax1.plot(self.asset_grid, self.choice_policies[d], lw=2, color=col, label=f"$c_{d}(M)$")
        c_exp = self.policy(self.asset_grid, choice=None)
        ax1.plot(self.asset_grid, c_exp, color="black", ls="--", lw=1.5, label="$E[c(M)]$")
        ax1.set_title("Consumption Policies")
        ax1.set_xlabel("Cash on Hand $M$")
        ax1.set_ylabel("Consumption $c$")
        ax1.legend(loc="best", frameon=True)
        ax1.grid(True, alpha=0.3)

        # Panel 2: Saving Policies
        ax2 = axes[0, 1]
        for d, col in zip(sorted(self.choice_policies.keys()), colors):
            a_prime_d = np.maximum(self.asset_grid - self.choice_policies[d], self.metadata.get("a_min", 0.0))
            ax2.plot(self.asset_grid, a_prime_d, lw=2, color=col, label=f"$a'_{d}(M)$")
        ax2.plot(self.asset_grid, self.asset_grid, color="gray", ls=":", alpha=0.7, label="$a'=M$")
        ax2.set_title("Next-Period Asset Policies $a' = M - c$")
        ax2.set_xlabel("Cash on Hand $M$")
        ax2.set_ylabel("Next Assets $a'$")
        ax2.legend(loc="best", frameon=True)
        ax2.grid(True, alpha=0.3)

        # Panel 3: Value Functions
        ax3 = axes[1, 0]
        for d, col in zip(sorted(self.choice_values.keys()), colors):
            ax3.plot(self.asset_grid, self.choice_values[d], lw=2, color=col, label=f"$v_{d}(M)$")
        ax3.plot(self.asset_grid, self.integrated_value, color="black", ls="--", lw=1.5, label="$V(M)$")
        ax3.set_title("Value Functions")
        ax3.set_xlabel("Cash on Hand $M$")
        ax3.set_ylabel("Value $V$")
        ax3.legend(loc="best", frameon=True)
        ax3.grid(True, alpha=0.3)

        # Panel 4: Choice Probabilities
        ax4 = axes[1, 1]
        for d, col in zip(sorted(self.choice_probabilities.keys()), colors):
            ax4.plot(self.asset_grid, self.choice_probabilities[d], lw=2, color=col, label=f"$P(d={d} \\mid M)$")
        ax4.set_title("Discrete Choice Probabilities")
        ax4.set_xlabel("Cash on Hand $M$")
        ax4.set_ylabel("Probability $P(d \\mid M)$")
        ax4.set_ylim(-0.05, 1.05)
        ax4.legend(loc="best", frameon=True)
        ax4.grid(True, alpha=0.3)

        if show:
            plt.show()
        return fig


