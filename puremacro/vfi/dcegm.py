class UpperEnvelopeResult(tuple):
    """Result of upper envelope filtering, unpackable as (policy, value)."""

    def __new__(
        cls,
        policy: np.ndarray,
        value: np.ndarray,
        grid: Optional[np.ndarray] = None,
    ):
        return super().__new__(cls, (policy, value))

    def __init__(
        self,
        policy: np.ndarray,
        value: np.ndarray,
        grid: Optional[np.ndarray] = None,
    ):
        self._policy = policy
        self._value = value
        self._grid = grid

    @property
    def policy(self) -> np.ndarray:
        """Filtered continuous choice policy on target exogenous grid."""
        return self._policy

    @property
    def value(self) -> np.ndarray:
        """Filtered value function on target exogenous grid."""
        return self._value

    @property
    def grid(self) -> Optional[np.ndarray]:
        """Target exogenous evaluation grid."""
        return self._grid

    @property
    def exog_grid(self) -> Optional[np.ndarray]:
        """Alias for target exogenous evaluation grid."""
        return self._grid

    @property
    def aprime(self) -> Optional[np.ndarray]:
        """Implied next-period asset policy a' = M - c."""
        if self._grid is not None:
            return np.maximum(self._grid - self._policy, 0.0)
        return None

    def __repr__(self) -> str:
        grid_len = len(self._grid) if self._grid is not None else len(self._policy)
        return f"UpperEnvelopeResult(points={grid_len}, policy_range=[{self._policy.min():.4g}, {self._policy.max():.4g}])"


# ---------------------------------------------------------------------------
# Upper Envelope Algorithm
# ---------------------------------------------------------------------------

def upper_envelope(
    endog_grid: Sequence[float] | np.ndarray,
    policy: Sequence[float] | np.ndarray,
    value: Sequence[float] | np.ndarray,
    exog_grid: Sequence[float] | np.ndarray,
    a_min: Optional[float] = None,
    v_cont_amin: Optional[float] = None,
    u_fn: Optional[Callable[[Union[float, np.ndarray]], Union[float, np.ndarray]]] = None,
    **kwargs: Any,
) -> UpperEnvelopeResult:
    r"""Upper Envelope algorithm filtering non-monotonic and sub-optimal branches.

    Evaluates the endogenous grid M(a') = a' + c(a'). Non-convexities in the
    continuation value induce non-monotonic folds where \partial M / \partial a' < 0.
    This algorithm partitions the raw endogenous points into strictly increasing
    segments, eliminates dominated / falling branches (local minima), compares
    competing branches in overlapping regions, and interpolates the optimal
    upper envelope onto `exog_grid`.

    Parameters
    ----------
    endog_grid : Sequence[float] | np.ndarray
        Raw endogenous cash-on-hand grid points M(a').
    policy : Sequence[float] | np.ndarray
        Raw choice policy (e.g. consumption c(a')).
    value : Sequence[float] | np.ndarray
        Raw choice value function v(a').
    exog_grid : Sequence[float] | np.ndarray
        Regular target exogenous evaluation grid for cash-on-hand M.
    a_min : float, optional
        Borrowing constraint lower bound on assets.
    v_cont_amin : float, optional
        Continuation value at borrowing limit a' = a_min.
    u_fn : Callable, optional
        Utility function for constrained region extrapolation.

    Returns
    -------
    UpperEnvelopeResult
        Tuple-like container unpackable as (c_filtered, v_filtered) with
        attributes .policy, .value, and .grid.
    """
    m_raw = np.asarray(endog_grid, dtype=np.float64)
    c_raw = np.asarray(policy, dtype=np.float64)
    v_raw = np.asarray(value, dtype=np.float64)
    exog = np.asarray(exog_grid, dtype=np.float64)

    n_raw = len(m_raw)
    if n_raw == 0:
        raise ValueError("endog_grid must not be empty.")
    if len(c_raw) != n_raw or len(v_raw) != n_raw:
        raise ValueError(
            f"Dimension mismatch: endog_grid ({n_raw}), policy ({len(c_raw)}), value ({len(v_raw)})."
        )
    if len(exog) == 0:
        raise ValueError("exog_grid must not be empty.")

    # 1. Identify continuous rising segments where M is strictly increasing
    # Each entry is (m_seg, c_seg, v_seg, is_constrained)
    segments: List[Tuple[np.ndarray, np.ndarray, np.ndarray, bool]] = []
    i = 0
    while i < n_raw:
        start = i
        while i < n_raw - 1 and m_raw[i + 1] >= m_raw[i]:
            i += 1
        end = i + 1
        if end - start >= 2:
            segments.append((m_raw[start:end], c_raw[start:end], v_raw[start:end], False))
        elif end - start == 1 and not segments:
            # Single-point fallback
            segments.append((m_raw[start:end], c_raw[start:end], v_raw[start:end], False))
        i = end
        # Skip over the falling branch (local minima violating second-order conditions)
        while i < n_raw - 1 and m_raw[i + 1] < m_raw[i]:
            i += 1
        i += 1

    if not segments:
        # Monotonic sorting fallback if no segmented pattern detected
        order = np.argsort(m_raw)
        segments.append((m_raw[order], c_raw[order], v_raw[order], False))

    # 2. Add constrained segment if cash-on-hand extends below lowest unconstrained M
    m_min_unconstrained = min(s[0][0] for s in segments)
    if a_min is not None and m_min_unconstrained > a_min:
        m_con = np.linspace(a_min, m_min_unconstrained, num=30)
        c_con = np.maximum(m_con - a_min, 1e-6)
        if u_fn is not None and v_cont_amin is not None:
            v_con = u_fn(c_con) + v_cont_amin
        else:
            slope_v = max((segments[0][2][1] - segments[0][2][0]) / max(segments[0][0][1] - segments[0][0][0], 1e-8), 0.1)
            v_con = segments[0][2][0] + slope_v * (m_con - m_min_unconstrained)
        segments.insert(0, (m_con, c_con, v_con, True))

    # 3. Evaluate each segment on the target exogenous grid
    v_candidates: List[np.ndarray] = []
    c_candidates: List[np.ndarray] = []
    m_min_global = min(s[0][0] for s in segments)

    for m_seg, c_seg, v_seg, is_con in segments:
        v_eval = np.interp(exog, m_seg, v_seg, left=-np.inf, right=-np.inf)
        c_eval = np.interp(exog, m_seg, c_seg, left=0.0, right=0.0)

        # Left extrapolation for lowest segment
        left_mask = exog < m_seg[0]
        if np.any(left_mask) and m_seg[0] <= m_min_global + 1e-5:
            denom = max(m_seg[1] - m_seg[0], 1e-8)
            slope_c = max((c_seg[1] - c_seg[0]) / denom, 0.1)
            slope_v = max((v_seg[1] - v_seg[0]) / denom, 0.1)
            c_eval[left_mask] = np.maximum(c_seg[0] + slope_c * (exog[left_mask] - m_seg[0]), 1e-6)
            v_eval[left_mask] = v_seg[0] + slope_v * (exog[left_mask] - m_seg[0])

        # Right extension: ONLY for unconstrained segments!
        # (A borrowing-constrained segment terminates at unconstrained threshold)
        if not is_con:
            right_mask = exog > m_seg[-1]
            if np.any(right_mask):
                denom = max(m_seg[-1] - m_seg[-2], 1e-8)
                slope_v = max((v_seg[-1] - v_seg[-2]) / denom, 1e-4)
                c_eval[right_mask] = c_seg[-1] + (exog[right_mask] - m_seg[-1])
                v_eval[right_mask] = v_seg[-1] + slope_v * (exog[right_mask] - m_seg[-1])

        v_candidates.append(v_eval)
        c_candidates.append(c_eval)

    v_mat = np.column_stack(v_candidates)
    c_mat = np.column_stack(c_candidates)

    # 4. Pointwise upper envelope maximum
    best_seg = np.argmax(v_mat, axis=1)
    v_clean = np.choose(best_seg, v_mat.T)
    c_clean = np.choose(best_seg, c_mat.T)

    # By free disposal / monotonicity of value functions, V(M) is non-decreasing
    v_clean = np.maximum.accumulate(v_clean)
    c_clean = np.maximum(c_clean, 1e-6)

    return UpperEnvelopeResult(c_clean, v_clean, exog)


