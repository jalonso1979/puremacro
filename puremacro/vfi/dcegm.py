# DCEGMProblem Class
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class DCEGMProblem:
    """Discrete Choice Endogenous Grid Method Problem.

    Parameters
    ----------
    a_grid : Sequence[float] | np.ndarray
        Exogenous grid of post-decision savings a' >= a_min.
    m_grid : Sequence[float] | np.ndarray | None, default None
        Exogenous target evaluation grid of cash-on-hand M. If None, constructed
        automatically spanning the feasible cash-on-hand range.
    n_choices : int, default 2
        Number of discrete choices d in {0, 1, ..., n_choices - 1}.
    u_fn : Callable[[np.ndarray, int], np.ndarray] | Sequence[Callable] | None, optional
        Utility function u(c, d). Default log utility with retirement disutility.
    u_prime : Callable[[np.ndarray, int], np.ndarray] | Sequence[Callable] | None, optional
        Marginal utility function u'(c, d). Default 1/c.
    u_prime_inv : Callable[[np.ndarray, int], np.ndarray] | Sequence[Callable] | None, optional
        Inverse marginal utility (u')^{-1}(w, d). Default 1/w.
    beta : float, default 0.96
        Discount factor beta in (0, 1).
    r : float, default 0.04
        Real interest rate r > -1 (gross rate R = 1 + r).
    income : Any, optional
        Income specification y(d) or y(d, z). Default [1.0, 0.4].
    P_z : np.ndarray, optional
        Markov transition matrix for shock z, shape (n_z, n_z). Default [[1.0]].
    z_grid : Sequence[float] | np.ndarray, optional
        Exogenous shock grid of length n_z. Default [1.0].
    sigma_eps : float, default 0.2
        Scale parameter of Extreme Value Type I taste shocks (sigma_eps >= 0).
    a_min : float, default 0.0
        Borrowing constraint lower bound on assets.
    horizon : int | None, default None
        Finite horizon periods T (if specified) or None for infinite horizon.
    discrete_transitions : np.ndarray | None, default None
        Feasibility transition matrix T(d' | d) across discrete choices.
    options : dict[str, Any] | None, default None
        Solver options: tol (default 1e-5), max_iter (default 1000).
    metadata : dict[str, Any] | None, default None
        User metadata.
    """

    a_grid: Sequence[float] | np.ndarray
    m_grid: Optional[Sequence[float] | np.ndarray] = None
    n_choices: int = 2
    u_fn: Optional[Any] = None
    u_prime: Optional[Any] = None
    u_prime_inv: Optional[Any] = None
    beta: float = 0.96
    r: float = 0.04
    income: Optional[Any] = None
    P_z: Optional[np.ndarray] = None
    z_grid: Optional[Sequence[float] | np.ndarray] = None
    sigma_eps: float = 0.2
    a_min: float = 0.0
    horizon: Optional[int] = None
    discrete_transitions: Optional[np.ndarray] = None
    options: Optional[Dict[str, Any]] = None
    metadata: Optional[Dict[str, Any]] = None

    def __post_init__(self) -> None:
        a_arr = np.asarray(self.a_grid, dtype=np.float64)

        if len(a_arr) < 2:
            raise ValueError("a_grid must have at least 2 points.")
        if np.any(np.diff(a_arr) <= 0):
            raise ValueError("a_grid must be strictly increasing.")
        if not (0.0 < self.beta < 1.0):
            raise ValueError(f"beta must be in (0, 1); got {self.beta}")
        if self.r <= -1.0:
            raise ValueError(f"r must be > -1; got {self.r}")
        if self.sigma_eps < 0.0:
            raise ValueError(f"sigma_eps must be >= 0; got {self.sigma_eps}")
        if self.n_choices < 2:
            raise ValueError(f"n_choices must be >= 2; got {self.n_choices}")

        if self.discrete_transitions is None:
            if self.n_choices == 2:
                # Canonical Iskhakov et al. (2017) retirement choice: retirement is absorbing
                object.__setattr__(
                    self, "discrete_transitions", np.array([[1.0, 1.0], [0.0, 1.0]], dtype=np.float64)
                )
            else:
                object.__setattr__(
                    self, "discrete_transitions", np.ones((self.n_choices, self.n_choices), dtype=np.float64)
                )

        if self.m_grid is None:
            # Construct default cash-on-hand grid spanning feasible range
            m_min = max(a_arr[0], self.a_min) + 1e-4
            m_max = max(1.25 * a_arr[-1] + 2.0, a_arr[-1] + 1.0)
            n_m = max(len(a_arr), 60)
            m_def = np.linspace(m_min, m_max, num=n_m)
            object.__setattr__(self, "m_grid", m_def)
        else:
            m_arr = np.asarray(self.m_grid, dtype=np.float64)
            if len(m_arr) < 2:
                raise ValueError("m_grid must have at least 2 points.")
            if np.any(np.diff(m_arr) <= 0):
                raise ValueError("m_grid must be strictly increasing.")
            object.__setattr__(self, "m_grid", m_arr)

    def _eval_u(self, c: np.ndarray, d: int) -> np.ndarray:
        """Evaluate utility u(c, d)."""
        if self.u_fn is not None:
            if callable(self.u_fn):
                return np.asarray(self.u_fn(c, d), dtype=np.float64)
            if isinstance(self.u_fn, (list, tuple)):
                return np.asarray(self.u_fn[d](c), dtype=np.float64)
        # Canonical default: log utility with retirement disutility of work (0.5 for d=0)
        c_safe = np.maximum(c, 1e-10)
        util = np.log(c_safe)
        if d == 0:
            util -= 0.5
        return util

    def _eval_u_prime(self, c: np.ndarray, d: int) -> np.ndarray:
        """Evaluate marginal utility u'(c, d)."""
        if self.u_prime is not None:
            if callable(self.u_prime):
                return np.asarray(self.u_prime(c, d), dtype=np.float64)
            if isinstance(self.u_prime, (list, tuple)):
                return np.asarray(self.u_prime[d](c), dtype=np.float64)
        c_safe = np.maximum(c, 1e-10)
        return 1.0 / c_safe

    def _eval_u_prime_inv(self, w: np.ndarray, d: int) -> np.ndarray:
        """Evaluate inverse marginal utility (u')^{-1}(w, d)."""
        if self.u_prime_inv is not None:
            if callable(self.u_prime_inv):
                return np.asarray(self.u_prime_inv(w, d), dtype=np.float64)
            if isinstance(self.u_prime_inv, (list, tuple)):
                return np.asarray(self.u_prime_inv[d](w), dtype=np.float64)
        w_safe = np.maximum(w, 1e-10)
        return 1.0 / w_safe

    def _get_income(self, d: int, zi: int = 0) -> float:
        """Retrieve income y(d, z)."""
        if self.income is None:
            # Default retirement model: y(0)=1.0, y(1)=0.4
            return 1.0 if d == 0 else 0.4
        if callable(self.income):
            try:
                return float(self.income(d, zi))
            except TypeError:
                return float(self.income(d))
        inc_arr = np.asarray(self.income, dtype=np.float64)
        if inc_arr.ndim == 1:
            return float(inc_arr[d])
        if inc_arr.ndim == 2:
            return float(inc_arr[d, zi])
        return float(inc_arr)

    def solve(self, backend: str = "numpy", **kwargs: Any) -> DCEGMSolution:
        """Solve the DC-EGM problem.

        Parameters
        ----------
        backend : str, default "numpy"
            Compute backend: "numpy", "numba", "mlx", or "cupy".
            Automatically falls back to "numpy" if requested accelerator is absent.
        **kwargs : Any
            Overrides for options (tol, max_iter).

        Returns
        -------
        DCEGMSolution
            Solved policy functions, conditional value functions, choice
            probabilities, integrated value, and presentation interface.
        """
        t0 = time.perf_counter()
        b = str(backend).strip().lower()

        if b not in _bk.SUPPORTED:
            raise ValueError(f"Unknown backend {backend!r}; supported: {_bk.SUPPORTED}")

        resolved_backend = b
        if not _bk.backend_available(b):
            warnings.warn(
                f"Backend {backend!r} requested but not available; falling back to 'numpy'.",
                UserWarning,
                stacklevel=2,
            )
            resolved_backend = "numpy"

        # Solver options
        opts = dict(self.options or {})
        opts.update(kwargs)
        tol = float(opts.get("tol", 1e-5))
        max_iter = int(opts.get("max_iter", 1000))

        a_grid = np.asarray(self.a_grid, dtype=np.float64)
        m_grid = np.asarray(self.m_grid, dtype=np.float64)
        n_a = len(a_grid)
        n_m = len(m_grid)
        n_d = self.n_choices
        R = 1.0 + self.r
        beta = self.beta
        sigma_eps = self.sigma_eps

        # Exogenous shocks
        P_z = np.asarray(self.P_z, dtype=np.float64) if self.P_z is not None else np.array([[1.0]])
        n_z = P_z.shape[0]

        # Discrete transitions T(d' | d): default all allowed
        if self.discrete_transitions is not None:
            T_d = np.asarray(self.discrete_transitions, dtype=np.float64)
        else:
            T_d = np.ones((n_d, n_d), dtype=np.float64)

        # Initialize terminal or initial guess
        # Shape: (n_d, n_m, n_z)
        c_curr = np.zeros((n_d, n_m, n_z), dtype=np.float64)
        v_curr = np.zeros((n_d, n_m, n_z), dtype=np.float64)

        for d in range(n_d):
            for zi in range(n_z):
                c_curr[d, :, zi] = np.maximum(m_grid - self.a_min, 1e-4)
                v_curr[d, :, zi] = self._eval_u(c_curr[d, :, zi], d)

        # Inclusive value initial
        v_inc_curr = np.zeros((n_m, n_z), dtype=np.float64)
        probs_curr = np.zeros((n_d, n_m, n_z), dtype=np.float64)
        for zi in range(n_z):
            v_inc_curr[:, zi], probs_curr[:, :, zi] = _logsumexp_probs_2d_kernel(
                v_curr[:, :, zi], sigma_eps
            )

        converged = False
        n_iter = 0
        sup_norm = np.inf

        is_finite = self.horizon is not None
        steps = self.horizon if is_finite else max_iter

        for it in range(1, steps + 1):
            n_iter = it
            c_next = c_curr.copy()
            v_next = v_curr.copy()
            c_new = np.zeros((n_d, n_m, n_z), dtype=np.float64)
            v_new = np.zeros((n_d, n_m, n_z), dtype=np.float64)

            for d in range(n_d):
                for zi in range(n_z):
                    # Next-period cash-on-hand for each feasible future choice d' and shock z'
                    # Compute expected continuation value and marginal value
                    w_cont = np.zeros(n_a, dtype=np.float64)
                    v_cont = np.zeros(n_a, dtype=np.float64)

                    for zj in range(n_z):
                        prob_z = P_z[zi, zj]
                        if prob_z <= 1e-12:
                            continue

                        # Future choice values and marginal values on next asset grid
                        v_fut = np.zeros((n_d, n_a), dtype=np.float64)
                        c_fut = np.zeros((n_d, n_a), dtype=np.float64)

                        for d_prime in range(n_d):
                            if T_d[d, d_prime] <= 1e-12:
                                v_fut[d_prime] = -1e300
                                c_fut[d_prime] = 1e-4
                                continue

                            M_prime = R * a_grid + self._get_income(d_prime, zj)
                            v_fut[d_prime] = np.interp(M_prime, m_grid, v_next[d_prime, :, zj])
                            c_fut[d_prime] = np.maximum(
                                np.interp(M_prime, m_grid, c_next[d_prime, :, zj]), 1e-4
                            )

                        # Inclusive value and choice probabilities for tomorrow
                        v_inc_prime, p_prime = _logsumexp_probs_2d_kernel(v_fut, sigma_eps)

                        # Envelope theorem expected marginal value of wealth without numerical diff!
                        # V'(M') = sum_{d'} P(d' | M') u'(c_{d'}(M'), d')
                        dV_prime = np.zeros(n_a, dtype=np.float64)
                        for d_prime in range(n_d):
                            if T_d[d, d_prime] > 1e-12:
                                u_p = self._eval_u_prime(c_fut[d_prime], d_prime)
                                dV_prime += p_prime[d_prime] * u_p

                        w_cont += prob_z * (beta * R * dV_prime)
                        v_cont += prob_z * (beta * v_inc_prime)

                    # Invert Euler equation: c = (u')^{-1}(w)
                    c_endog = self._eval_u_prime_inv(w_cont, d)
                    m_endog = a_grid + c_endog
                    v_endog = self._eval_u(c_endog, d) + v_cont

                    # Upper envelope filtering
                    v_amin = float(v_cont[0])
                    res_ue = upper_envelope(
                        m_endog,
                        c_endog,
                        v_endog,
                        m_grid,
                        a_min=self.a_min,
                        v_cont_amin=v_amin,
                        u_fn=lambda c_: self._eval_u(c_, d),
                    )
                    c_new[d, :, zi] = res_ue.policy
                    v_new[d, :, zi] = res_ue.value

            # Update inclusive value and probabilities
            v_inc_new = np.zeros((n_m, n_z), dtype=np.float64)
            probs_new = np.zeros((n_d, n_m, n_z), dtype=np.float64)
            for zi in range(n_z):
                v_inc_new[:, zi], probs_new[:, :, zi] = _logsumexp_probs_2d_kernel(
                    v_new[:, :, zi], sigma_eps
                )

            # Check convergence (policy sup-norm, standard in EGM algorithms)
            sup_norm = float(np.max(np.abs(c_new - c_curr)))
            c_curr = c_new
            v_curr = v_new
            v_inc_curr = v_inc_new
            probs_curr = probs_new

            if not is_finite and sup_norm < tol:
                converged = True
                break
        else:
            if is_finite:
                converged = True
            else:
                converged = sup_norm < tol

        elapsed = time.perf_counter() - t0

        # Package solution dictionaries using ChoiceMapping for dict and array duality
        choice_policies_dict: Dict[int, np.ndarray] = {}
        choice_values_dict: Dict[int, np.ndarray] = {}
        choice_probabilities_dict: Dict[int, np.ndarray] = {}

        for d in range(n_d):
            if n_z == 1:
                choice_policies_dict[d] = c_curr[d, :, 0]
                choice_values_dict[d] = v_curr[d, :, 0]
                choice_probabilities_dict[d] = probs_curr[d, :, 0]
            else:
                choice_policies_dict[d] = c_curr[d]
                choice_values_dict[d] = v_curr[d]
                choice_probabilities_dict[d] = probs_curr[d]

        choice_policies = ChoiceMapping(choice_policies_dict)
        choice_values = ChoiceMapping(choice_values_dict)
        choice_probabilities = ChoiceMapping(choice_probabilities_dict)

        int_val = v_inc_curr[:, 0] if n_z == 1 else v_inc_curr

        meta = {
            "converged": converged,
            "n_iter": n_iter,
            "sup_norm": sup_norm,
            "backend": resolved_backend,
            "elapsed_time": elapsed,
            "sigma_eps": sigma_eps,
            "beta": beta,
            "r": self.r,
            "a_min": self.a_min,
            "horizon": self.horizon,
            "n_choices": n_d,
            "n_a": n_a,
            "n_m": n_m,
            "n_z": n_z,
        }

        return DCEGMSolution(
            asset_grid=m_grid,
            choice_policies=choice_policies,
            choice_values=choice_values,
            choice_probabilities=choice_probabilities,
            integrated_value=int_val,
            converged=converged,
            metadata=meta,
        )


