def solve_dcegm(
    problem_or_a_grid: Union[DCEGMProblem, Sequence[float], np.ndarray],
    m_grid: Optional[Union[Sequence[float], np.ndarray]] = None,
    *args: Any,
    backend: str = "numpy",
    **kwargs: Any,
) -> DCEGMSolution:
    """Functional interface for solving discrete-continuous dynamic programs via DC-EGM.

    Accepts either a configured `DCEGMProblem` instance or raw grid/parameter arguments.

    Parameters
    ----------
    problem_or_a_grid : DCEGMProblem | Sequence[float] | np.ndarray
        Either a pre-built `DCEGMProblem` or next-period asset grid `a_grid`.
    m_grid : Sequence[float] | np.ndarray, optional
        Target evaluation grid for cash-on-hand M (if a_grid passed as first arg).
    backend : str, default "numpy"
        Compute backend: "numpy", "numba", "mlx", or "cupy".
    **kwargs : Any
        Additional keyword arguments passed to `DCEGMProblem` or `.solve()`.

    Returns
    -------
    DCEGMSolution
        Solved policy functions, conditional value functions, choice probabilities,
        integrated value, and presentation interface.
    """
    if isinstance(problem_or_a_grid, DCEGMProblem):
        return problem_or_a_grid.solve(backend=backend, **kwargs)

    # Extract problem kwargs vs solver kwargs
    problem_keys = {
        "n_choices", "u_fn", "u_prime", "u_prime_inv", "beta", "r",
        "income", "P_z", "z_grid", "sigma_eps", "a_min", "horizon",
        "discrete_transitions", "options", "metadata",
    }
    prob_kwargs = {k: v for k, v in kwargs.items() if k in problem_keys}
    solve_kwargs = {k: v for k, v in kwargs.items() if k not in problem_keys}

    problem = DCEGMProblem(
        a_grid=problem_or_a_grid,
        m_grid=m_grid,
        **prob_kwargs,
    )
    return problem.solve(backend=backend, **solve_kwargs)


