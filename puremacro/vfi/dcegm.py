@_bk.njit_fallback(fastmath=True)
def _logsumexp_probs_1d_kernel(v: np.ndarray, sigma_eps: float) -> Tuple[float, np.ndarray]:
    """Compute log-sum-exp inclusive value and multinomial logit probabilities."""
    n = len(v)
    v_max = -1e300
    for i in range(n):
        if v[i] > v_max:
            v_max = v[i]

    if sigma_eps <= 1e-12:
        # Deterministic choice limit
        ties = 0
        for i in range(n):
            if abs(v[i] - v_max) < 1e-12:
                ties += 1
        probs = np.zeros(n, dtype=np.float64)
        for i in range(n):
            if abs(v[i] - v_max) < 1e-12:
                probs[i] = 1.0 / float(ties)
        return v_max, probs

    sum_exp = 0.0
    probs = np.zeros(n, dtype=np.float64)
    for i in range(n):
        val = np.exp((v[i] - v_max) / sigma_eps)
        probs[i] = val
        sum_exp += val

    v_inc = v_max + sigma_eps * np.log(sum_exp)
    for i in range(n):
        probs[i] /= sum_exp

    return v_inc, probs


@_bk.njit_fallback(fastmath=True)
def _logsumexp_probs_2d_kernel(
    v_mat: np.ndarray, sigma_eps: float
) -> Tuple[np.ndarray, np.ndarray]:
    """Compute log-sum-exp and choice probabilities across discrete choices (axis 0)."""
    n_d, n_m = v_mat.shape
    v_inc = np.zeros(n_m, dtype=np.float64)
    probs = np.zeros((n_d, n_m), dtype=np.float64)

    for m in range(n_m):
        v_col = v_mat[:, m]
        v_max = -1e300
        for d in range(n_d):
            if v_col[d] > v_max:
                v_max = v_col[d]

        if sigma_eps <= 1e-12:
            ties = 0
            for d in range(n_d):
                if abs(v_col[d] - v_max) < 1e-12:
                    ties += 1
            for d in range(n_d):
                if abs(v_col[d] - v_max) < 1e-12:
                    probs[d, m] = 1.0 / float(ties)
                else:
                    probs[d, m] = 0.0
            v_inc[m] = v_max
        else:
            sum_exp = 0.0
            for d in range(n_d):
                val = np.exp((v_col[d] - v_max) / sigma_eps)
                probs[d, m] = val
                sum_exp += val
            v_inc[m] = v_max + sigma_eps * np.log(sum_exp)
            for d in range(n_d):
                probs[d, m] /= sum_exp

    return v_inc, probs


