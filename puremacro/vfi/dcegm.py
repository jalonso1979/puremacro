"""Discrete Choice Endogenous Grid Method (DC-EGM) & Upper Envelope Filtering.

Implements the Discrete Choice Endogenous Grid Method of Iskhakov, Jørgensen,
Rust & Schjerning (2017) for dynamic economic models with continuous
consumption/saving choices and discrete choices (e.g., retirement, labor force
participation, default).

Key Components:
1. `upper_envelope`: Fast upper envelope algorithm filtering non-monotonic
   and sub-optimal branches of the endogenous grid generated by non-convex
   value functions, detecting crossing points and interpolating onto target grids.
2. `DCEGMProblem`: Frozen dataclass defining discrete-continuous dynamic programs,
   supporting Extreme Value Type I taste shocks (logit choice probabilities),
   envelope-theorem marginal value calculations without numerical differentiation,
   deterministic choice limits (sigma_eps -> 0), and multi-backend acceleration.
3. `DCEGMSolution`: Frozen dataclass containing continuous choice policies,
   values, choice probabilities, integrated value, and presentation methods
   (.summary(), .plot(), .to_frame(), .to_markdown(), .to_latex(), .to_typst()).
4. `solve_dcegm`: Functional entry point for solving discrete-continuous problems.
"""
